# Kept in YAML so interface copy can be maintained independently of the runtime.
_WORKSPACE_TRANSLATIONS = Path(__file__).resolve().parents[2] / "egs/ui_translations.yaml"
TRANSLATIONS.update(yaml.safe_load(_WORKSPACE_TRANSLATIONS.read_text(encoding="utf-8")))


def _normalize_text(text: str) -> str:
    """Normalize browser-rendered labels before dictionary lookup."""

    return " ".join(str(text or "").strip().split())


def translations_json() -> str:
    """Serialize the dictionary for embedding into the frontend JS payload."""

    return json.dumps(TRANSLATIONS, ensure_ascii=False, separators=(",", ":"))


def technical_texts_json() -> str:
    """Serialize backend field and enum labels for client-side bilingual rendering."""

    return json.dumps(TECHNICAL_TEXT_LABELS, ensure_ascii=False, separators=(",", ":"))


def translate(text: str) -> str:
    """Translate a single Chinese UI string (fallback: original text)."""

    normalized = _normalize_text(text)
    return TRANSLATIONS.get(normalized, text)


def translate_technical(text: str, language: str = LANGUAGE_CN) -> str:
    """Translate a backend field or enum token to a deterministic display label."""

    normalized = _normalize_text(text)
    labels = TECHNICAL_TEXT_LABELS.get(normalized)
    if not labels:
        return text
    target_language = LANGUAGE_EN if language == LANGUAGE_EN else LANGUAGE_CN
    return labels.get(target_language, text)
